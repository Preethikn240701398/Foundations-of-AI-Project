async def seed_if_needed():
    """Create / refresh the catalogue when the seed version changes (user data is never touched)."""
    meta = await db.col("meta").find_one({"_id": "seed"})
    if not meta or meta.get("version") != SEED_VERSION:
        for name in ("meals", "foods", "workouts"):
            await db.col(name).delete_many({})
        for m in MEALS:
            await db.col("meals").insert_one({**m, "_id": oid(), "created_at": utcnow()})
        for f in FOODS:
            await db.col("foods").insert_one({**f, "_id": oid()})
        for w in WORKOUTS:
            await db.col("workouts").insert_one({**w, "_id": oid()})
        await db.col("meta").update_one({"_id": "seed"}, {"$set": {"version": SEED_VERSION}}, upsert=True)


async def all_serialized(name: str):
    docs = await db.col(name).find({}).to_list(1000)
    return [serialize(d) for d in docs]
